#!/usr/bin/env python3
"""sync_cursor_skills.py — generate .cursor/skills/<name>/SKILL.md pointers for every skills/genseo-*/SKILL.md.

Cursor discovers project skills only under .cursor/skills/ (or .agents/skills/), never under a repo-root
skills/, and symlinked skill folders are not a documented feature — so each canonical skill gets a real pointer
file that carries the same name + description and sends the agent to the canonical SKILL.md. The canonical
files stay where the Macs, the headless runner prompt and AGENTS.md already expect them.

  python3 scripts/sync_cursor_skills.py           # write / refresh the pointers
  python3 scripts/sync_cursor_skills.py --check   # exit 1 if a pointer is missing, stale or orphaned
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "skills")
DST = os.path.join(ROOT, ".cursor", "skills")
NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
BLOCK = {">", "|", ">-", "|-", ">+", "|+"}


def frontmatter(path):
    """Top-level scalar keys of a SKILL.md frontmatter (plain, quoted, or folded/literal block)."""
    lines = open(path, encoding="utf-8").read().split("\n")
    if not lines or lines[0].strip() != "---":
        return {}
    out, key, block = {}, None, []
    for ln in lines[1:]:
        if ln.strip() == "---":
            break
        if key and (ln.startswith((" ", "\t")) or not ln.strip()):
            block.append(ln.strip())
            continue
        if key:
            out[key], key = " ".join(b for b in block if b), None
        k, sep, v = ln.partition(":")
        if not sep or ln.startswith((" ", "\t")):
            continue
        k, v = k.strip(), v.strip()
        if v in BLOCK:
            key, block = k, []
        else:
            out[k] = v[1:-1] if len(v) > 1 and v[0] == v[-1] and v[0] in "\"'" else v
    if key:
        out[key] = " ".join(b for b in block if b)
    return out


def pointer(name, desc):
    return f"""---
name: {name}
description: {json.dumps(desc, ensure_ascii=False)}
---

# {name}

Canonical skill: `skills/{name}/SKILL.md` (repo root). Read it in full and follow it exactly — this file only
exists so Cursor discovers the skill. Relative paths inside it (`references/`, `scripts/`) resolve against
`skills/{name}/`; `~/genseo` and `/Users/kevinkreative/genseo` mean the repo root.

Apply `.cursor/rules/genseo-operating-rules.mdc` first: from a cloud VM there is no publishing, no Shopify write,
no image generation and no persona pick unless Kevin explicitly asks.

Generated by `scripts/sync_cursor_skills.py` from the canonical file — edit that file, then re-run the script.
"""


def wanted():
    want, errors = {}, []
    for path in sorted(glob.glob(os.path.join(SRC, "genseo-*", "SKILL.md"))):
        folder = os.path.basename(os.path.dirname(path))
        fm = frontmatter(path)
        name, desc = fm.get("name", ""), fm.get("description", "").strip()
        if name != folder:
            errors.append(f"skills/{folder}/SKILL.md: name {name!r} must equal the folder name")
        elif not NAME.match(name) or len(name) > 64:
            errors.append(f"skills/{folder}/SKILL.md: name must be lowercase letters/digits/hyphens, ≤64 chars")
        elif not desc:
            errors.append(f"skills/{folder}/SKILL.md: missing description")
        else:
            if len(desc) > 1024:
                desc = desc[:1023].rsplit(" ", 1)[0] + "…"
            want[name] = pointer(name, desc)
    return want, errors


def main():
    check = "--check" in sys.argv
    want, errors = wanted()
    for e in errors:
        print(f"✗ {e}")
    if not want:
        print("✗ no skills/genseo-*/SKILL.md found")
        return 1
    drift = []
    for name, text in want.items():
        path = os.path.join(DST, name, "SKILL.md")
        cur = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if cur == text:
            continue
        drift.append(f"{'stale' if cur is not None else 'missing'}: .cursor/skills/{name}/SKILL.md")
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    have = {d for d in os.listdir(DST) if os.path.isdir(os.path.join(DST, d))} if os.path.isdir(DST) else set()
    orphans = sorted(d for d in have if d.startswith("genseo-") and d not in want)
    for d in orphans:
        print(f"✗ orphan: .cursor/skills/{d} has no skills/{d}/SKILL.md — move it to _superseded/")
    if check:
        for d in drift:
            print(f"✗ {d}")
        ok = not (drift or orphans or errors)
        print(f"{'✓' if ok else '✗'} {len(want)} skill pointer(s) checked, {len(drift)} out of date, {len(orphans)} orphaned")
        return 0 if ok else 1
    print(f"✓ {len(want)} skill pointer(s) in .cursor/skills ({len(drift)} written)")
    return 1 if (orphans or errors) else 0


if __name__ == "__main__":
    sys.exit(main())
